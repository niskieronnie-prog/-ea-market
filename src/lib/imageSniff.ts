/** Identify real image type from magic bytes. Never trust the filename or declared MIME type. */
export function sniffImage(b: Uint8Array): "jpeg" | "png" | "webp" | null {
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "jpeg";
  if (b.length >= 8 && [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a].every((v, i) => b[i] === v)) return "png";
  if (b.length >= 12 && String.fromCharCode(...b.slice(0, 4)) === "RIFF" && String.fromCharCode(...b.slice(8, 12)) === "WEBP") return "webp";
  return null;
}
export function sniffPdf(b: Uint8Array): boolean {
  return b.length >= 5 && String.fromCharCode(...b.slice(0, 5)) === "%PDF-";
}
